package ex6arraymultidimensional.expratico2;

//Crie uma variável inteira e informe se o número é par ou ímpar.

public class Main {
    public static void main(String[] args) {
        int numero = 10;

        if (numero % 2 == 0) {
            System.out.println("O número é par.");
        } else {
            System.out.println("O número é ímpar.");
        }
    }
}