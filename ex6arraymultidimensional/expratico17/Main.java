package ex6arraymultidimensional.expratico17;

//Utilize for-each para exibir todos os nomes.

public class Main {
    public static void main(String[] args) {

        String[] nomes = {
            "Ana",
            "Carlos",
            "Maria",
            "João",
            "Pedro"
        };

        for (String nome : nomes) {
            System.out.println(nome);
        }
    }
}