//Crie duas variáveis inteiras e mostre qual delas é maior.
 
public class Main {
    public static void main(String[] args) {
        int numero1 = 10;
        int numero2 = 20;

        if (numero1 > numero2) {
            System.out.println("O maior número é: " + numero1);
        } else {
            System.out.println("O maior número é: " + numero2);
        }
    }
}

