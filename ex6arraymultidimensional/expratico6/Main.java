package ex6arraymultidimensional.expratico6;

//Mostre todos os números pares de 1 até 100

public class Main {
    public static void main(String[] args) {

        for (int i = 1; i <= 100; i++) {
            if (i % 2 == 0) {
                System.out.println(i);
            }
        }

    }
}
